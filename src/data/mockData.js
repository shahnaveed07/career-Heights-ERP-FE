export function generateInitialAttendanceRecords(studentsList) {
  const dates = [];
  for (let i = 9; i >= 0; i--) {
    dates.push(getPastDateString(i));
  }
  const records = [];
  for (const s of studentsList) {
    const targetPresent = Math.max(
      1,
      Math.round((s.attendanceRate / 100) * dates.length)
    );
    dates.forEach((dateStr, idx) => {
      let status = 'present';
      if (idx >= targetPresent) {
        status = idx % 2 === 0 ? 'absent' : 'late';
      }
      records.push({
        id: `att-${s.id}-${dateStr}`,
        studentId: s.id,
        studentName: s.name,
        studentCode: s.studentId,
        batchId: s.batchId,
        batchName: s.batchName,
        branchId: s.branchId,
        date: dateStr,
        status,
        checkInTime:
          status === 'present' || status === 'late' ? '08:30 AM' : void 0,
        markedBy: 'Faculty / Mentor',
      });
    });
  }
  return records;
}
